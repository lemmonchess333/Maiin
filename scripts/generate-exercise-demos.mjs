#!/usr/bin/env node
/**
 * Exercise visual-demo generator — D-LIFT-20, revived + upgraded (2026-07).
 * OPERATOR-RUN, NOT CI.
 *
 * History: the first pilot shipped a Squat start/finish pair (#1447) that was
 * reverted (#1448) because the generated coach (shaded illustration, face,
 * skin tones) clashed with the app's flat-vector muscle-map figure, and the
 * tooling was then deleted (#1449). The product owner overrode that revert
 * (2026-07-04): custom demos ARE wanted — so this revival attacks the #1448
 * objection head-on instead of abandoning the idea:
 *
 *   1. STYLE ANCHOR — every request now includes the app's ACTUAL muscle-map
 *      figure (scripts/assets/tropos-figure-ref.png, cropped from the live
 *      Form view) as a style reference. Nano Banana's strength is
 *      character-consistent editing; give it the real Tropos body and ask it
 *      to pose THAT figure.
 *   2. N-FRAME SEQUENCES (--frames, default 4) — not just start/finish. Each
 *      frame is generated by EDITING the previous frame (consistency chain),
 *      walking the range of motion top → bottom. The in-app player ping-pongs
 *      the ordered frames, so one-way keyframes yield a full rep loop.
 *   3. QA CONTACT SHEET — writes _preview.html next to the output with an
 *      animated flipbook per exercise (same cadence as the app player) plus
 *      the exercise's instructions, so review is minutes, not file-spelunking.
 *
 * THE HARD RULE IS UNCHANGED: a WRONG demo is worse than none. Every frame
 * MUST be eyeballed against the exercise's instructions before its `media`
 * is wired into exercises.ts. This script only PRODUCES candidates; a human
 * gates them.
 *
 * Usage (Codespaces or any Node 18+ shell):
 *   GEMINI_API_KEY=… node scripts/generate-exercise-demos.mjs --only squat
 *   GEMINI_API_KEY=… node scripts/generate-exercise-demos.mjs --limit 30
 *   GEMINI_API_KEY=… node scripts/generate-exercise-demos.mjs --only deadlift --frames 5
 *
 * Output:
 *   public/exercise-demos/<id>/frame-1..N.<ext> + manifest.json + _preview.html
 *
 * After QA, paste each id's emitted `media:` snippet into src/lib/exercises.ts
 * (after that exercise's `regressions:` line — see squat for the shape).
 */
import { readFileSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = resolve(ROOT, "public/exercise-demos");
const REF_PATH = resolve(ROOT, "scripts/assets/tropos-figure-ref.png");
const MODEL = "gemini-2.5-flash-image"; // "Nano Banana"
const API = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;

// Curated pilot set — the big compounds + most-used accessories. Keep ≤ ~30;
// scale only after a batch passes QA.
const TOP_LIFTS = [
  "bench-press",
  "incline-db-press",
  "overhead-press",
  "db-shoulder-press",
  "barbell-row",
  "db-row",
  "lat-pulldown",
  "pull-ups",
  "squat",
  "front-squat",
  "leg-press",
  "romanian-deadlift",
  "deadlift",
  "hip-thrust",
  "bulgarian-split",
  "barbell-curl",
  "db-curl",
  "hammer-curl",
  "rope-tricep-pushdown",
  "overhead-extension",
  "lateral-raise",
  "calf-raise",
];

// The style contract. The first inline image on EVERY request is the app's
// real muscle-map figure; the prompt keeps pointing the model back at it.
// NOTE: any purple tint the model paints is COSMETIC, not data-accurate —
// the volume-driven muscle readout stays the MuscleHeatMap SVG.
const TROPOS_STYLE =
  "Match the FIRST reference image's art style EXACTLY: a flat, faceted, " +
  "low-poly vector anatomy figure made of angular light-grey segments with " +
  "thin dark seams, on a very dark charcoal background. Abstract featureless " +
  "head — NO face, NO hair, NO skin tones, NO gradients or soft shading, NO " +
  "outlines thicker than the reference's seams. The muscles primarily working " +
  "in this movement are filled soft purple exactly like the reference's " +
  "highlighted segments. Equipment (barbell / dumbbells / bench / cable) is " +
  "drawn as simple flat dark-grey vector shapes. ONE single figure, full body " +
  "in frame, side three-quarter camera angle, no text, no watermark. " +
  "Anatomically correct joints, limb count and grip.";

function exerciseInfo(id, src) {
  const block = src.split(`id: "${id}"`)[1]?.split(/\n  \{/)[0] ?? "";
  const name = block.match(/name:\s*"([^"]+)"/)?.[1] ?? id;
  const instructions = [...block.matchAll(/"([^"]+)"/g)]
    .map((m) => m[1])
    .filter((s) => s.length > 25)
    .slice(0, 5);
  return { name, instructions };
}

/** Pose description for frame k of n along the one-way top→bottom walk. */
function beatPrompt(k, n, name, cue) {
  if (k === 0) {
    return (
      `${TROPOS_STYLE} Pose the reference figure at the TOP of the range of ` +
      `motion for a ${name} — the fully-extended / lockout position that ` +
      `begins and ends the rep (standing tall for a squat, arms locked out ` +
      `for a press, hanging at full extension for a pull-up).${cue}`
    );
  }
  const isBottom = k === n - 1;
  const fraction =
    n <= 2 ? "" : ` about ${Math.round((k / (n - 1)) * 100)}% of the way`;
  const where = isBottom
    ? `the BOTTOM of the range of motion — the deepest / most-flexed point ` +
      `of the rep (a deep squat with hips at or below parallel and torso ` +
      `upright; the bar at the chest for a press; chin over the bar for a ` +
      `pull-up)`
    : `an INTERMEDIATE position${fraction} from the top toward the bottom ` +
      `of the rep — joints partially bent, clearly between the previous ` +
      `frame's pose and the bottom position`;
  return (
    `Re-pose the SAME single figure from the SECOND image (the previous ` +
    `frame). Keep its exact faceted flat-vector style, colours, purple ` +
    `muscle fills, camera framing and background — style must keep matching ` +
    `the FIRST reference image. Show EXACTLY ONE figure; do NOT add a second ` +
    `person; do NOT keep the previous pose. Move the figure to ${where} for ` +
    `a ${name}. The pose MUST be visibly different from the previous ` +
    `frame.${cue}`
  );
}

async function generate(prompt, refImage, baseImage) {
  const parts = [{ text: prompt }];
  if (refImage)
    parts.push({ inlineData: { mimeType: refImage.mime, data: refImage.data } });
  if (baseImage)
    parts.push({
      inlineData: { mimeType: baseImage.mime, data: baseImage.data },
    });
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(`${API}?key=${process.env.GEMINI_API_KEY}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ contents: [{ parts }] }),
    });
    if (res.status === 429 || res.status >= 500) {
      const wait = 4000 * (attempt + 1);
      console.log(`    (HTTP ${res.status} — retrying in ${wait / 1000}s)`);
      await new Promise((r) => setTimeout(r, wait));
      continue;
    }
    if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
    const json = await res.json();
    const img = json.candidates?.[0]?.content?.parts?.find(
      (p) => p.inlineData
    )?.inlineData;
    if (!img) throw new Error("no image in response");
    return { mime: img.mimeType, data: img.data };
  }
  throw new Error("rate-limited after 3 attempts");
}

const ext = (mime) =>
  mime.includes("webp") ? "webp" : mime.includes("jpeg") ? "jpg" : "png";

function writePreview(results, src) {
  const cards = Object.entries(results)
    .map(([id, frames]) => {
      const { name, instructions } = exerciseInfo(id, src);
      const imgs = frames
        .map((f) => `<img src="${f.split("/").slice(1).join("/")}" alt="">`)
        .join("");
      const framesJson = JSON.stringify(
        frames.map((f) => f.split("/").slice(1).join("/"))
      );
      return `<section>
  <h2>${name} <small>(${id})</small></h2>
  <div class="strip">${imgs}</div>
  <div class="play" data-frames='${framesJson}'><img alt="animated preview"></div>
  <ol>${instructions.map((i) => `<li>${i}</li>`).join("")}</ol>
</section>`;
    })
    .join("\n");
  const html = `<!doctype html><meta charset="utf-8"><title>Demo QA</title>
<style>
body{font-family:system-ui;background:#121214;color:#eee;max-width:960px;margin:2rem auto;padding:0 1rem}
section{border:1px solid #333;border-radius:12px;padding:1rem;margin:1rem 0}
.strip img{width:130px;border-radius:8px;margin-right:6px}
.play img{width:220px;border-radius:8px}
h2 small{color:#888;font-weight:400}
ol{color:#aaa;font-size:.85rem}
</style>
<h1>Exercise demo QA — eyeball every frame against the instructions</h1>
<p>The animated box replays frames at the app player's cadence (ping-pong).
Reject anything with wrong joints, extra limbs/figures, wrong grip, or style
drift from the muscle-map look. Delete bad frames and regenerate with
<code>--only &lt;id&gt;</code>.</p>
${cards}
<script>
document.querySelectorAll('.play').forEach(box=>{
  const frames=JSON.parse(box.dataset.frames);const img=box.querySelector('img');
  let i=0,dir=1;img.src=frames[0];
  setInterval(()=>{i+=dir;if(i>=frames.length-1){i=frames.length-1;dir=-1}
  else if(i<=0){i=0;dir=1}img.src=frames[i];},700);
});
</script>`;
  writeFileSync(resolve(OUT_DIR, "_preview.html"), html);
}

async function main() {
  if (!process.env.GEMINI_API_KEY) {
    console.error("Set GEMINI_API_KEY. This script is operator-run, never CI.");
    process.exit(1);
  }
  if (!existsSync(REF_PATH)) {
    console.error(`Missing style reference: ${REF_PATH}`);
    process.exit(1);
  }
  const refImage = {
    mime: "image/png",
    data: readFileSync(REF_PATH).toString("base64"),
  };

  const limit = Number(process.argv[process.argv.indexOf("--limit") + 1]) || 30;
  const frames = Math.min(
    Math.max(
      Number(process.argv[process.argv.indexOf("--frames") + 1]) || 4,
      2
    ),
    6
  );
  const onlyArg = process.argv[process.argv.indexOf("--only") + 1];
  const only =
    process.argv.includes("--only") && onlyArg && !onlyArg.startsWith("--")
      ? new Set(onlyArg.split(",").map((s) => s.trim()))
      : null;
  const src = readFileSync(resolve(ROOT, "src/lib/exercises.ts"), "utf8");

  const targets = only
    ? TOP_LIFTS.filter((id) => only.has(id))
    : TOP_LIFTS.slice(0, limit);
  if (only && targets.length === 0) {
    console.error(`--only matched no ids. Known: ${TOP_LIFTS.join(", ")}`);
    process.exit(1);
  }

  // Merge with any existing manifest so re-running --only doesn't nuke
  // previously generated entries.
  const manifestPath = resolve(OUT_DIR, "manifest.json");
  const manifest = existsSync(manifestPath)
    ? JSON.parse(readFileSync(manifestPath, "utf8"))
    : {};

  for (const id of targets) {
    const { name, instructions } = exerciseInfo(id, src);
    const cue = instructions.length ? ` Form: ${instructions.join(" ")}` : "";
    console.log(`→ ${id} (${name}) — ${frames} frames`);
    try {
      const outFrames = [];
      let prev = null;
      for (let k = 0; k < frames; k++) {
        process.stdout.write(`    frame ${k + 1}/${frames}… `);
        const img = await generate(beatPrompt(k, frames, name, cue), refImage, prev);
        const dir = resolve(OUT_DIR, id);
        mkdirSync(dir, { recursive: true });
        const file = `frame-${k + 1}.${ext(img.mime)}`;
        writeFileSync(resolve(dir, file), Buffer.from(img.data, "base64"));
        outFrames.push(`exercise-demos/${id}/${file}`);
        prev = img;
        console.log("ok");
        // Gentle pacing for free-tier quotas.
        await new Promise((r) => setTimeout(r, 1500));
      }
      manifest[id] = outFrames;
      console.log(`    media snippet for exercises.ts (${id}):`);
      console.log(
        `    media: [\n${outFrames.map((f) => `      "${f}",`).join("\n")}\n    ],`
      );
    } catch (e) {
      console.error(`  ✗ ${id}: ${e.message}`);
    }
  }

  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
  writePreview(manifest, src);
  console.log(
    `\nDone. Open public/exercise-demos/_preview.html in a browser and QA ` +
      `every exercise against its instructions. Delete/regen bad ones ` +
      `(--only <id>), then paste the printed media snippets into ` +
      `src/lib/exercises.ts and commit the reviewed assets.`
  );
}

main();
