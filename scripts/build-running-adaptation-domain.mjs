/** Generate the real TypeScript planner/catalogue for the CommonJS server.
 * --check fails on drift; it never silently repairs a checked-in artifact.
 */
import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "functions/lib/generated/runningAdaptationDomain.cjs");
const result = await build({ absWorkingDir: root, entryPoints: ["src/features/program/runningAdaptationServerDomain"], bundle: true,
  platform: "node", target: "node22", format: "cjs", write: false, legalComments: "none", charset: "utf8", sourcemap: false,
  tsconfig: "tsconfig.app.json", banner: { js: "// Generated by scripts/build-running-adaptation-domain.mjs. Do not edit." } });
const generated = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== generated) throw Error("Running adaptation server artifact is stale; regenerate it.");
} else {
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, generated);
}
