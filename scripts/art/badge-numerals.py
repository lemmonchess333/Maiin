#!/usr/bin/env python3
"""The numerals a badge carries in its art (DS4 call 4, DESIGN_GUIDE §14m
rule 27), as outlines of the display cut: Archivo, wide (wdth 125), black
(wght 900), italic, the cut the finish screen's display figure is set in
(`.ds-display-figure`). A badge is an <img>, which loads no web font, so
the figures go into the SVG as paths and the art stays in the app's two
families.

Reads the installed @fontsource-variable/archivo build (the one the app
ships), instances it at those axes, and writes each glyph's outline in font
units (y up, 1000 to the em) with its advance:

    python3 scripts/art/badge-numerals.py

Writes src/features/streaks/badgeArt/numerals.data.ts. Needs fontTools and
brotli (`pip install fonttools brotli`).
"""
import json
import os
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FONT = os.path.join(
    ROOT,
    "node_modules/@fontsource-variable/archivo/files/archivo-latin-wdth-italic.woff2",
)
OUT = os.path.join(ROOT, "src/features/streaks/badgeArt/numerals.data.ts")
AXES = {"wght": 900, "wdth": 125}
CHARS = "0123456789Kkmt.:+"


class PathPen(BasePen):
    """An outline as SVG path data in M, L, Q, C and Z only (no H or V, so
    every number pair is a point and the app can move and scale them
    without a path parser), each point rounded to a whole font unit: a
    thousandth of the em is far below a pixel at any size a badge is
    drawn."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.parts = []

    def _pt(self, *pts):
        return " ".join(f"{round(x)} {round(y)}" for x, y in pts)

    def _moveTo(self, pt):
        self.parts.append("M" + self._pt(pt))

    def _lineTo(self, pt):
        self.parts.append("L" + self._pt(pt))

    def _curveToOne(self, a, b, c):
        self.parts.append("C" + self._pt(a, b, c))

    def _qCurveToOne(self, a, b):
        self.parts.append("Q" + self._pt(a, b))

    def _closePath(self):
        self.parts.append("Z")

    def d(self):
        return "".join(self.parts)


def main() -> None:
    font = TTFont(FONT)
    version = font["name"].getDebugName(5)
    inst = instantiateVariableFont(font, AXES)
    glyph_set = inst.getGlyphSet()
    cmap = inst.getBestCmap()
    hmtx = inst["hmtx"]
    glyphs = {}
    for ch in CHARS:
        name = cmap[ord(ch)]
        pen = PathPen(glyph_set)
        glyph_set[name].draw(pen)
        glyphs[ch] = {"d": pen.d(), "advance": hmtx[name][0]}
    data = {
        "unitsPerEm": inst["head"].unitsPerEm,
        "capHeight": inst["OS/2"].sCapHeight,
        "xHeight": inst["OS/2"].sxHeight,
        "glyphs": glyphs,
    }
    header = (
        "/**\n"
        " * GENERATED by scripts/art/badge-numerals.py. Do not edit.\n"
        " *\n"
        f" * Archivo {version}, wdth {AXES['wdth']}, wght {AXES['wght']}, italic: the\n"
        " * display cut, as outlines in font units (y up). A badge's numerals\n"
        " * are drawn from these (DS4 call 4).\n"
        " */\n"
    )
    body = (
        "export const BADGE_NUMERALS = "
        + json.dumps(data, indent=2, ensure_ascii=False)
        + " as const;\n"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(header + "\n" + body)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(glyphs)} glyphs)", file=sys.stderr)


if __name__ == "__main__":
    main()
