/**
 * Cut out the Food diary's drawings: the food pictures in docs/food-art,
 * keyed out of their black backdrop by the same keying as the exercise
 * cut-outs (keying.ts), then centred on a 192 px square, which is a diary
 * row's 48 pt picture at three times (DS4, DESIGN_GUIDE §14m rule 25).
 * docs/food-art/provenance.json says how each was drawn.
 *
 * Writes public/food-art/<kind>.webp and src/lib/foodArt.data.ts, which
 * records each source's and output's hash; foodArt.test.ts fails when a
 * source changes and its cut-out was not regenerated.
 *
 *   npm run art:food
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import sharp from "sharp";
import { formatGenerated } from "./format-generated";
import { cutoutWebp } from "./keying";

const ROOT = resolve(import.meta.dirname, "..", "..");
const MANIFEST = resolve(ROOT, "src/lib/foodArt.data.ts");
const KINDS = [
  "bowl",
  "eggs",
  "bread",
  "salad",
  "fruit",
  "protein",
  "grains",
  "drink",
  "sweet",
  "plate",
] as const;
const SIDE = 192;

const sha256 = (bytes: Buffer) =>
  createHash("sha256").update(bytes).digest("hex");

async function main() {
  const rows: string[] = [];
  for (const kind of KINDS) {
    const source = `docs/food-art/${kind}.jpg`;
    const sourceBytes = readFileSync(resolve(ROOT, source));
    const { webp: keyed } = await cutoutWebp(resolve(ROOT, source));
    const webp = await sharp(keyed)
      .resize(SIDE, SIDE, {
        fit: "contain",
        background: { r: 0, g: 0, b: 0, alpha: 0 },
        kernel: "lanczos3",
      })
      .webp({ quality: 86, alphaQuality: 90, effort: 6 })
      .toBuffer();
    const src = `food-art/${kind}.webp`;
    writeFileSync(resolve(ROOT, "public", src), webp);
    rows.push(
      `  ${kind}: { src: "${src}", source: "${source}", ` +
        `sourceSha256: "${sha256(sourceBytes)}", sha256: "${sha256(webp)}" },`
    );
    console.log(`${kind.padEnd(8)} ${(webp.length / 1024).toFixed(1)} KB`);
  }
  const text = `/* GENERATED by \`npm run art:food\` (scripts/art/cut-out-food-art.ts).
   Do not edit by hand: re-run the script when a drawing changes.
   foodArt.test.ts re-hashes every source and output listed here. */

export type FoodArtKind = ${KINDS.map((kind) => `"${kind}"`).join(" | ")};

export interface FoodArtCutout {
  /** Public path of the transparent cut-out, a ${SIDE} px square. */
  src: string;
  /** The drawing it was cut from. */
  source: string;
  sourceSha256: string;
  sha256: string;
}

export const FOOD_ART: Record<FoodArtKind, FoodArtCutout> = {
${rows.join("\n")}
};
`;
  writeFileSync(MANIFEST, await formatGenerated(MANIFEST, text));
  console.log(`wrote ${KINDS.length} cut-outs and ${MANIFEST}`);
}

await main();
