const KNOWN = new Set(CARD_ART_IDS);

/** The drawing's address on troposfit.com, or undefined for an id that
 *  is not a released cut-out. */
function cardArtSrc(id) {
  return typeof id === "string" && KNOWN.has(id)
    ? `/form-art/${id}.webp`
    : undefined;
}

