import { describe, expect, it } from "vitest";
import { createRequire } from "node:module";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { serverDomainPlan } from "../runningAdaptationServerDomain";
const require = createRequire(import.meta.url);
const { serverDomainPlan: server } = require("../../../../functions/lib/generated/runningAdaptationDomain.cjs") as { serverDomainPlan: typeof serverDomainPlan };
function fixture() {
  return {
    nowMs: Date.parse("2026-11-06T12:00:00Z"), windowStart: "2026-11-09",
    selections: [{ sessionId: "one", maxMinutes: 25, format: { kind: "easy" } }],
    authority: { schemaVersion: 1, accountId: "runner", revision: 8, timeZone: "UTC", holds: [] as string[], manualCompletions: {},
      constraints: { symptoms: "none", capacity: { confirmed: true, afterEffectsReviewed: true, daysPerWeek: 2, longestMinutes: 25 }, restrictions: { status: "none" },
        reviewConfirmation: { version: 1, confirmed: true, authorityRevision: 8, raceGoalId: "race" } },
      plan: { raceGoalId: "race", sessions: [{ id: "one", date: "2026-11-09", templateId: "easy_40", minutes: 40, kind: "easy", status: "planned" }, { id: "two", date: "2026-11-11", templateId: "easy_30", minutes: 30, kind: "easy", status: "planned" }] } },
  };
}
function errorCode(fn: () => unknown) {
  try { fn(); return "unexpected-success"; } catch (error) { return (error as { code: string }).code; }
}
describe("canonical server domain and generated planner artifact", () => {
  it("is regenerated byte-for-byte from real source and catalogue", () => {
    execFileSync(process.execPath, [fileURLToPath(new URL("../../../../scripts/build-running-adaptation-domain.mjs", import.meta.url)), "--check"]);
  });
  it("produces identical actual template output without mutating authority", () => {
    const input = fixture(); const before = structuredClone(input);
    const output = serverDomainPlan(input);
    expect(output.plan.sessions).toEqual([{ id: "one", date: "2026-11-09", minutes: 20, kind: "easy", templateId: "easy_20" }]);
    expect(server(input)).toEqual(output); expect(input).toEqual(before);
  });
  const invalid = [
    ["hold", (f: ReturnType<typeof fixture>) => { f.authority.holds = ["injury"]; }],
    ["unknown canonical constraint", (f: ReturnType<typeof fixture>) => { Object.assign(f.authority.constraints, { noHills: true }); }],
    ["unknown review schema field", (f: ReturnType<typeof fixture>) => { Object.assign(f.authority.constraints.reviewConfirmation, { clinicalClearance: true }); }],
    ["missing review", (f: ReturnType<typeof fixture>) => { Object.assign(f.authority.constraints, { reviewConfirmation: undefined }); }],
    ["stale review", (f: ReturnType<typeof fixture>) => { f.authority.constraints.reviewConfirmation.authorityRevision = 7; }],
    ["wrong goal", (f: ReturnType<typeof fixture>) => { f.authority.constraints.reviewConfirmation.raceGoalId = "other"; }],
    ["unknown symptoms", (f: ReturnType<typeof fixture>) => { f.authority.constraints.symptoms = "unknown"; }],
    ["unsupported restrictions", (f: ReturnType<typeof fixture>) => { Object.assign(f.authority.constraints.restrictions, { maxHillGrade: 5 }); }],
    ["no running", (f: ReturnType<typeof fixture>) => { Object.assign(f.authority.constraints, { restrictions: { status: "specified", source: "clinician", noRunning: true } }); }],
    ["protected", (f: ReturnType<typeof fixture>) => { Object.assign(f.authority.plan.sessions[0], { protected: true }); }],
    ["completed", (f: ReturnType<typeof fixture>) => { f.authority.plan.sessions[0].status = "completed_exact"; }],
    ["manual", (f: ReturnType<typeof fixture>) => { f.authority.manualCompletions = { one: {} }; }],
    ["same day", (f: ReturnType<typeof fixture>) => { f.windowStart = "2026-11-06"; }],
    ["timezone", (f: ReturnType<typeof fixture>) => { f.authority.timeZone = "invalid"; }],
    ["client marker", (f: ReturnType<typeof fixture>) => { Object.assign(f.selections[0], { validation: { policyVersion: 1 } }); }],
    ["duplicate date", (f: ReturnType<typeof fixture>) => { f.authority.plan.sessions[1].date = f.authority.plan.sessions[0].date; f.selections.push({ ...f.selections[0], sessionId: "two" }); }],
    ["canonical duration mismatch", (f: ReturnType<typeof fixture>) => { f.authority.plan.sessions[0].minutes = 10; }],
    ["canonical kind mismatch", (f: ReturnType<typeof fixture>) => { f.authority.plan.sessions[0].kind = "quality"; }],
    ["unknown template", (f: ReturnType<typeof fixture>) => { f.authority.plan.sessions[0].templateId = "client_easy_1"; }],
    ["unconfirmed capacity", (f: ReturnType<typeof fixture>) => { f.authority.constraints.capacity.confirmed = false; }],
  ] as const;
  it.each(invalid)("source and server both reject %s", (_name, mutate) => {
    const f = fixture(); mutate(f); const before = structuredClone(f);
    const expected = errorCode(() => serverDomainPlan(f));
    expect(expected).not.toBe("unexpected-success"); expect(errorCode(() => server(f))).toBe(expected); expect(f).toEqual(before);
  });
  it("uses the authority timezone rather than UTC for future-window validation", () => {
    const f = fixture(); f.nowMs = Date.parse("2026-11-08T15:00:00Z"); f.authority.timeZone = "Pacific/Kiritimati";
    expect(errorCode(() => server(f))).toBe("window-not-future");
  });
});
